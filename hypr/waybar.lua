function M.write(style, path)
    path = path or (os.getenv("HOME") .. "/.config/waybar/style.css")

    local f, err = io.open(path, "w")
    if not f then
        error("failed to open Waybar CSS output: " .. tostring(err))
    end

    f:write(M.css(style))
    f:close()
end

return M
