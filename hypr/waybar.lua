-- File: waybar.lua
--
-- Renderer for Waybar style.css.
-- Input:  style table from base.lua / green_teal.lua
-- Output: ~/.config/waybar/style.css
--
-- This file is code. The style files remain pure data.

local M = {}

local function strip_hash(color)
    return tostring(color):gsub("^#", "")
end

local function css_color(color)
    if color == nil then
        return "transparent"
    end

    if color == "transparent" then
        return "transparent"
    end

    if color:match("^#") then
        return color
    end

    return "#" .. color
end

local function hex_to_rgba(color, alpha)
    if color == nil or color == "transparent" then
        return "transparent"
    end

    local hex = strip_hash(color)

    if #hex ~= 6 then
        error("hex_to_rgba expects #rrggbb, got: " .. tostring(color))
    end

    local r = tonumber(hex:sub(1, 2), 16)
    local g = tonumber(hex:sub(3, 4), 16)
    local b = tonumber(hex:sub(5, 6), 16)

    return string.format("rgba(%d, %d, %d, %.3f)", r, g, b, alpha)
end

local function q(s)
    return '"' .. tostring(s):gsub('"', '\\"') .. '"'
end

